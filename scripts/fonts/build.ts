import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import subsetFont from "subset-font";
import { loadIconCatalog, missingIcons, scanIconNames } from "./icon-names";

export const fontDirectory = "public/fonts";
export const manifestPath = "src/routes/font-manifest.ts";

/** Weights served from the single variable Inter file (the faces the site always requested). */
export const interWeights = [400, 500, 600, 700] as const;
const interSubsets = ["latin", "latin-ext"] as const;
const interRoot = "node_modules/@fontsource-variable/inter";
const licenses = {
  "LICENSE-Inter-OFL-1.1.txt": `${interRoot}/LICENSE`,
  "LICENSE-Material-Symbols-Apache-2.0.txt": "node_modules/material-symbols/LICENSE",
};
// Material Symbols pinned to FILL 0, GRAD 0, wght 400. The 20..24 optical-size range keeps the
// `font: 400 20px` ::before icons and the explicit "opsz" 24 settings rendering as they did.
const iconAxes = { FILL: 0, GRAD: 0, wght: 400, opsz: { min: 20, max: 24 } };
const iconLetters = "abcdefghijklmnopqrstuvwxyz0123456789_";

export interface FontBuild {
  /** File name inside public/fonts → bytes. */
  files: Map<string, Uint8Array>;
  /** Contents of src/routes/font-manifest.ts. */
  manifest: string;
  iconNames: string[];
}

const hash = (data: Uint8Array) => createHash("sha256").update(data).digest("hex").slice(0, 10);
const hashed = (name: string, data: Uint8Array) => `${name}.${hash(data)}.woff2`;

function unicodeRange(root: string, subset: string): string {
  const css = readFileSync(join(root, interRoot, "wght.css"), "utf8");
  const match = css.match(new RegExp(`/\\* inter-${subset}-wght-normal \\*/[^}]*?unicode-range:\\s*([^;]+);`));
  if (!match) throw new Error(`No unicode-range for Inter ${subset}`);
  return match[1].trim();
}

export function assertIcons(font: Uint8Array, names: readonly string[]): void {
  const missing = missingIcons(font, names);
  if (missing.length) throw new Error(`Icon subset lost ligatures: ${missing.join(", ")}`);
}

export async function buildFonts(root: string): Promise<FontBuild> {
  const files = new Map<string, Uint8Array>();
  const interFaces: { subset: string; file: string; unicodeRange: string }[] = [];
  for (const subset of interSubsets) {
    const range = unicodeRange(root, subset);
    const source = readFileSync(join(root, interRoot, "files", `inter-${subset}-wght-normal.woff2`));
    // Keep Fontsource's glyph set (already split by unicode-range); only narrow the weight axis.
    const data = await subsetFont(source, "", { targetFormat: "woff2", keepAllGlyphs: true, variationAxes: { wght: { min: 400, max: 700 } } });
    const file = hashed(`inter-${subset}`, data);
    files.set(file, data);
    interFaces.push({ subset, file, unicodeRange: range });
  }

  const catalog = loadIconCatalog(root);
  const iconNames = scanIconNames(root, catalog);
  const codePoints = iconNames.map(name => String.fromCodePoint(catalog.get(name) as number)).join("");
  // Retain the letters the ligature rules match plus each icon's own glyph. Layout closure is off:
  // it would pull in every ligature spelled from those letters, i.e. the whole 4 MB font.
  const icons = await subsetFont(readFileSync(join(root, "node_modules/material-symbols/material-symbols-outlined.woff2")),
    iconLetters + codePoints, { targetFormat: "woff2", noLayoutClosure: true, variationAxes: iconAxes });
  const iconFile = hashed("material-symbols-outlined", icons);
  files.set(iconFile, icons);
  assertIcons(icons, iconNames);

  for (const [name, source] of Object.entries(licenses)) files.set(name, readFileSync(join(root, source)));

  const manifest = `// Generated by scripts/build-fonts.ts (pnpm build:fonts). Do not edit.
export const fontManifest = ${JSON.stringify({ inter: { weights: interWeights, faces: interFaces }, icons: { file: iconFile, names: iconNames } }, null, 2)} as const;
`;
  return { files, manifest, iconNames };
}

/** Differences between a build and the committed files; empty when they match byte for byte. */
export function diffFontBuild(root: string, build: FontBuild): string[] {
  const problems: string[] = [];
  const directory = join(root, fontDirectory);
  const existing = existsSync(directory) ? readdirSync(directory) : [];
  for (const [name, data] of build.files) {
    const path = join(directory, name);
    if (!existsSync(path)) problems.push(`${fontDirectory}/${name} is missing`);
    else if (!Buffer.from(data).equals(readFileSync(path))) problems.push(`${fontDirectory}/${name} differs from the generated file`);
  }
  for (const name of existing) if (!build.files.has(name)) problems.push(`${fontDirectory}/${name} is stale`);
  const manifestFile = join(root, manifestPath);
  if (!existsSync(manifestFile) || readFileSync(manifestFile, "utf8") !== build.manifest) problems.push(`${manifestPath} is out of date`);
  return problems;
}

export function writeFontBuild(root: string, build: FontBuild): void {
  const directory = join(root, fontDirectory);
  mkdirSync(directory, { recursive: true });
  for (const name of readdirSync(directory)) if (!build.files.has(name)) rmSync(join(directory, name));
  for (const [name, data] of build.files) writeFileSync(join(directory, name), data);
  writeFileSync(join(root, manifestPath), build.manifest);
}

/** CLI behaviour: regenerate, or with --check verify the committed output and fail on drift. */
export async function runFontBuild(root: string, args: string[], log: (message: string) => void = console.log): Promise<number> {
  const build = await buildFonts(root);
  if (args.includes("--check")) {
    const problems = diffFontBuild(root, build);
    if (problems.length) {
      log(`${problems.join("\n")}\nRun pnpm build:fonts and commit the result.`);
      return 1;
    }
    log(`Fonts verified (${build.iconNames.length} icons).`);
    return 0;
  }
  writeFontBuild(root, build);
  log(`Built ${build.files.size} font files (${build.iconNames.length} icons).`);
  return 0;
}
