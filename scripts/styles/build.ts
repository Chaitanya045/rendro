import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const styleDirectory = "public/styles";
export const manifestPath = "src/routes/style-manifest.ts";
/** Stylesheet name → committed source. Each is served under a content-hashed name. */
export const styleSources = { "viewer-base": "src/styles/viewer-base.css" } as const;

export interface StyleBuild {
  /** File name inside public/styles → bytes. */
  files: Map<string, Uint8Array>;
  /** Contents of src/routes/style-manifest.ts. */
  manifest: string;
}

const hash = (data: Uint8Array) => createHash("sha256").update(data).digest("hex").slice(0, 10);

export function buildStyles(root: string): StyleBuild {
  const files = new Map<string, Uint8Array>();
  const names: Record<string, string> = {};
  for (const [name, source] of Object.entries(styleSources)) {
    const data = new Uint8Array(readFileSync(join(root, source)));
    const file = `${name}.${hash(data)}.css`;
    files.set(file, data);
    names[name] = file;
  }
  const manifest = `// Generated by scripts/build-styles.ts (pnpm build:styles). Do not edit.
export const styleManifest = ${JSON.stringify(names, null, 2)} as const;
`;
  return { files, manifest };
}

/** Differences between a build and the committed files; empty when they match byte for byte. */
export function diffStyleBuild(root: string, build: StyleBuild): string[] {
  const problems: string[] = [];
  const directory = join(root, styleDirectory);
  const existing = existsSync(directory) ? readdirSync(directory) : [];
  for (const [name, data] of build.files) {
    const path = join(directory, name);
    if (!existsSync(path)) problems.push(`${styleDirectory}/${name} is missing`);
    else if (!Buffer.from(data).equals(readFileSync(path))) problems.push(`${styleDirectory}/${name} differs from its source`);
  }
  for (const name of existing) if (!build.files.has(name)) problems.push(`${styleDirectory}/${name} is stale`);
  const manifestFile = join(root, manifestPath);
  if (!existsSync(manifestFile) || readFileSync(manifestFile, "utf8") !== build.manifest) problems.push(`${manifestPath} is out of date`);
  return problems;
}

export function writeStyleBuild(root: string, build: StyleBuild): void {
  const directory = join(root, styleDirectory);
  mkdirSync(directory, { recursive: true });
  for (const name of readdirSync(directory)) if (!build.files.has(name)) rmSync(join(directory, name));
  for (const [name, data] of build.files) writeFileSync(join(directory, name), data);
  writeFileSync(join(root, manifestPath), build.manifest);
}

/** CLI behaviour: regenerate, or with --check verify the committed output and fail on drift. */
export function runStyleBuild(root: string, args: string[], log: (message: string) => void = console.log): number {
  const build = buildStyles(root);
  if (args.includes("--check")) {
    const problems = diffStyleBuild(root, build);
    if (problems.length) {
      log(`${problems.join("\n")}\nRun pnpm build:styles and commit the result.`);
      return 1;
    }
    log(`Styles verified (${build.files.size} files).`);
    return 0;
  }
  writeStyleBuild(root, build);
  log(`Built ${build.files.size} style files.`);
  return 0;
}
